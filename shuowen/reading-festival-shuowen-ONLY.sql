-- 《說文解圖》2026 臺灣閱讀節限定版：唯一需要執行的 SQL
-- 在目前既有 Supabase 專案 SQL Editor 執行一次；可重複執行。
-- 只新增 rf_sw_ 前綴物件，不碰原版房間、兒時記趣排行榜、書院學籍及詩情畫意資料。

create table if not exists public.rf_sw_scores (
  id bigint generated by default as identity primary key,
  player_name text not null,
  name_key text generated always as (lower(btrim(player_name))) stored,
  game_id text not null check (game_id in ('room','child')),
  total_score integer not null check (total_score between 0 and 3000),
  achieved_at timestamptz not null default now(),
  constraint rf_sw_scores_name_unique unique (name_key),
  constraint rf_sw_scores_name_valid check (char_length(btrim(player_name)) between 1 and 12)
);

alter table public.rf_sw_scores enable row level security;
revoke all on table public.rf_sw_scores from public, anon, authenticated;

-- 資料表不直接授權瀏覽器寫入；僅可由下方受限 RPC 更新最高分。
create or replace function public.rf_sw_submit_score(
  p_player_name text,
  p_game_id text,
  p_total_score integer
) returns void
language plpgsql security definer set search_path = public, pg_temp
as $$
declare
  v_name text := btrim(p_player_name);
  v_limit integer;
begin
  if v_name is null or char_length(v_name) < 1 or char_length(v_name) > 12 then
    raise exception '姓名長度必須在 1 至 12 字之間';
  end if;
  if p_game_id not in ('room','child') or p_game_id is null then
    raise exception '不支援的篇章';
  end if;
  v_limit := case p_game_id when 'room' then 2220 when 'child' then 2580 end;
  if p_total_score is null or p_total_score < 0 or p_total_score > v_limit then
    raise exception '分數超出允許範圍';
  end if;
  insert into public.rf_sw_scores (player_name, game_id, total_score)
  values(v_name,p_game_id,p_total_score)
  on conflict (name_key) do update
   set player_name=excluded.player_name,
       game_id=excluded.game_id,
       total_score=excluded.total_score,
       achieved_at=now()
   where excluded.total_score > public.rf_sw_scores.total_score;
end;
$$;

revoke all on function public.rf_sw_submit_score(text,text,integer) from public;
grant execute on function public.rf_sw_submit_score(text,text,integer) to anon, authenticated;

-- 無個資帳號、僅公開暱稱、篇章、原始得分、達成時間。
create or replace view public.rf_sw_leaderboard as
select player_name, game_id, total_score, achieved_at
from public.rf_sw_scores;
revoke all on public.rf_sw_leaderboard from public;
grant select on public.rf_sw_leaderboard to anon, authenticated;

